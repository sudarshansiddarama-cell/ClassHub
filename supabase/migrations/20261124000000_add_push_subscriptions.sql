-- ClassHub: Web Push subscriptions table.
--
-- Stores push subscriptions so the send-push Edge Function can deliver
-- notifications even when ClassHub is closed.
--
-- Apply with:  node scripts/deploy-supabase.mjs
-- or paste into the Supabase Dashboard SQL Editor.

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.push_subscriptions enable row level security;

-- Users can manage only their own subscriptions.
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'push_subscriptions'
      and policyname = 'Users manage own push subscriptions'
  ) then
    create policy "Users manage own push subscriptions"
      on public.push_subscriptions
      for all
      to authenticated
      using ( auth.uid() = user_id )
      with check ( auth.uid() = user_id );
  end if;
end $$;

