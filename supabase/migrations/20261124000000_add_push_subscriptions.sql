-- ClassHub: Web Push subscriptions table.
--
-- Stores push subscriptions so the send-push Edge Function can deliver
-- notifications even when ClassHub is closed.
--
-- APPLY MANUALLY (Supabase CLI is unavailable on Android and the saved
-- access token is invalid). Run this in the Supabase SQL Editor once:
--   supabase db push   (if CLI were available)
-- or paste into the Supabase Dashboard SQL Editor.
--
-- After applying, deploy supabase/functions/send-push/index.ts and set the
-- VAPID_PRIVATE_KEY secret to the base64url-encoded EC private key that
-- matches VAPID_PUBLIC_KEY in index.html.

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.push_subscriptions enable row level security;

-- Users can manage only their own subscriptions.
create policy if not exists "Users manage own push subscriptions"
  on public.push_subscriptions
  for all
  to authenticated
  using ( auth.uid() = user_id )
  with check ( auth.uid() = user_id );

-- The send-push Edge Function (service role) can read all subscriptions.
create policy if not exists "Service role reads all push subscriptions"
  on public.push_subscriptions
  for select
  to authenticated  -- Edge Functions use service-role key, bypassing RLS
  using ( true );
